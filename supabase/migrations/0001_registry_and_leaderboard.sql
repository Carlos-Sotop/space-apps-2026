-- SpaceDAO shared state: published blueprints (Open Tech Registry) and the mission leaderboard.
-- Play data only: no accounts, no personal data, no money. Anyone can read; the browser (publishable key,
-- role "anon") can only INSERT rows that pass the checks below. Nobody can update or delete from the browser.
-- Apply once in the Supabase SQL editor (or `psql "$DATABASE_URL" -f this-file`). Safe to run twice.

-- ---------------------------------------------------------------------------
-- blueprints
-- ---------------------------------------------------------------------------
create table if not exists public.blueprints (
  id            text primary key check (id ~ '^bp-player-[a-z0-9]{1,24}$'),
  name          text not null check (char_length(name) between 1 and 60),
  author_id     text not null check (author_id ~ '^[a-z0-9-]{1,40}$'),
  parent_id     text check (parent_id is null or char_length(parent_id) between 1 and 60),
  category      text not null check (category in (
                  'bus','power','battery','comms','computer','adcs','propulsion','thermal',
                  'lander','instrument','experiment','habitat','isru','rover')),
  modifiers     jsonb not null default '[]'::jsonb
                  check (jsonb_typeof(modifiers) = 'array' and jsonb_array_length(modifiers) <= 8),
  summary       text not null default '' check (char_length(summary) <= 160),
  content_hash  text not null check (content_hash ~ '^[0-9a-f]{64}$'),
  tx_hash       text check (tx_hash is null or char_length(tx_hash) between 20 and 100),
  adoptions     integer not null default 0 check (adoptions >= 0),
  created_at    timestamptz not null default now()
);

create index if not exists blueprints_created_idx on public.blueprints (created_at desc);
create index if not exists blueprints_parent_idx  on public.blueprints (parent_id);

-- ---------------------------------------------------------------------------
-- missions (leaderboard)
-- ---------------------------------------------------------------------------
create table if not exists public.missions (
  id             uuid primary key default gen_random_uuid(),
  mission_id     text not null check (mission_id in ('orbital-lab','earth-guardian','moon-base-zero')),
  lead_id        text not null check (lead_id ~ '^[a-z0-9-]{1,40}$'),
  -- generated by the game (e.g. "ESA-7K2Q"), never typed by the player: keeps personal data out
  callsign       text not null check (callsign ~ '^[A-Za-z0-9-]{3,24}$'),
  score          integer not null check (score between 0 and 10000),
  grade          text not null check (grade in ('S','A','B','C','F')),
  success        boolean not null,
  lost_at        text check (lost_at is null or char_length(lost_at) <= 24),
  science        integer not null check (science between 0 and 10000),
  safety         integer not null check (safety between 0 and 10000),
  efficiency     integer not null check (efficiency between 0 and 10000),
  collaboration  integer not null check (collaboration between 0 and 10000),
  manifest_hash  text check (manifest_hash is null or manifest_hash ~ '^[0-9a-f]{64}$'),
  tx_hash        text check (tx_hash is null or char_length(tx_hash) between 20 and 100),
  created_at     timestamptz not null default now()
);

create index if not exists missions_board_idx on public.missions (mission_id, score desc, created_at);

-- ---------------------------------------------------------------------------
-- row level security
-- ---------------------------------------------------------------------------
alter table public.blueprints enable row level security;
alter table public.missions   enable row level security;

revoke all on public.blueprints from anon, authenticated;
revoke all on public.missions   from anon, authenticated;
grant select, insert on public.blueprints to anon, authenticated;
grant select, insert on public.missions   to anon, authenticated;

drop policy if exists "blueprints are public"       on public.blueprints;
drop policy if exists "anyone can publish a blueprint" on public.blueprints;
drop policy if exists "missions are public"         on public.missions;
drop policy if exists "anyone can post a mission"   on public.missions;

create policy "blueprints are public" on public.blueprints
  for select to anon, authenticated using (true);

-- new rows start with zero adoptions and may not claim a transaction signature the relayer never made
create policy "anyone can publish a blueprint" on public.blueprints
  for insert to anon, authenticated
  with check (adoptions = 0 and tx_hash is null);

create policy "missions are public" on public.missions
  for select to anon, authenticated using (true);

create policy "anyone can post a mission" on public.missions
  for insert to anon, authenticated
  with check (tx_hash is null);

-- No update or delete policy exists, so the browser cannot change or remove rows.
-- The browser cannot prove a score was earned: the leaderboard is for fun, not for prizes.
